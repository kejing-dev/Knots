"""Knots icon (design `appIcon`): a hemp rope tied as a figure eight, the last bit of the working end orange, dark
seams where a strand crosses over another, on harbour teal. One drawing, two outputs:

    python -I tools/make_icon.py <export.png>      # the 512 PNG for the showcase
    python -I tools/make_icon.py --xml             # writes app/src/main/res/drawable/ic_launcher_foreground.xml

Strands are cubic Bézier paths in the 108 x 108 adaptive-icon viewport; later strands are drawn over earlier ones.
"""
import os
import sys

TEAL = "#13788C"
HEMP = "#EDE3CF"
ORANGE = "#F26B1D"
SEAM = "#0E5A69"
ROPE_W = 6.4
SEAM_W = 10.0

# (colour, seam under it?, path) ; paths: M x,y then C x1,y1 x2,y2 x,y ... / L x,y
_RAW = [
    (HEMP, False, [("M", 54, 20), ("L", 54, 36), ("C", 54, 44, 69, 45, 69, 53), ("C", 69, 61, 39, 61, 39, 71), ("C", 39, 82, 69, 82, 69, 71), ("C", 69, 64, 60, 60, 54, 57)]),
    (HEMP, True, [("M", 54, 57), ("C", 45, 53, 38, 49, 38, 42), ("C", 38, 33, 51, 31, 57, 37), ("C", 60, 40, 62, 44, 62, 50)]),
    (ORANGE, True, [("M", 62, 50), ("C", 62, 54, 62, 58, 61.8, 62), ("L", 61.5, 82)]),
]
# the glyph is drawn at 0.72 about the centre so it stays inside the launcher's visible circle
_K = 0.72


def _scaled(c):
    vals = [54 + (v - 54) * _K for v in c[1:]]
    return (c[0],) + tuple(round(v, 2) for v in vals)


STRANDS = [(col, seam, [_scaled(c) for c in cmds]) for col, seam, cmds in _RAW]
ROPE_W = ROPE_W * _K / 0.72 * 0.72 / 0.72 * 0.9
SEAM_W = SEAM_W * 0.9


def svg_path(cmds):
    out = []
    for c in cmds:
        if c[0] == "M":
            out.append("M%g,%g" % c[1:])
        elif c[0] == "L":
            out.append("L%g,%g" % c[1:])
        else:
            out.append("C%g,%g %g,%g %g,%g" % c[1:])
    return " ".join(out)


def write_xml(path):
    lines = [
        "<!-- Generated by tools/make_icon.py: figure-eight knot, hemp rope with an orange working end. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
    ]
    for colour, seam, cmds in STRANDS:
        d = svg_path(cmds)
        if seam:
            lines.append('    <path android:pathData="%s" android:strokeColor="#FF%s" android:strokeWidth="%g" android:strokeLineCap="butt" android:fillColor="#00000000"/>' % (d, SEAM[1:], SEAM_W))
        lines.append('    <path android:pathData="%s" android:strokeColor="#FF%s" android:strokeWidth="%g" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>' % (d, colour[1:], ROPE_W))
    lines.append("</vector>")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("xml written", path)


def sample(cmds, steps=40):
    pts = []
    cur = None
    for c in cmds:
        if c[0] == "M":
            cur = (c[1], c[2])
            pts.append(cur)
        elif c[0] == "L":
            for i in range(1, steps + 1):
                t = i / steps
                pts.append((cur[0] + (c[1] - cur[0]) * t, cur[1] + (c[2] - cur[1]) * t))
            cur = (c[1], c[2])
        else:
            x1, y1, x2, y2, x, y = c[1:]
            for i in range(1, steps + 1):
                t = i / steps
                a = (1 - t) ** 3
                b = 3 * (1 - t) ** 2 * t
                cc = 3 * (1 - t) * t * t
                d = t ** 3
                pts.append((a * cur[0] + b * x1 + cc * x2 + d * x, a * cur[1] + b * y1 + cc * y2 + d * y))
            cur = (x, y)
    return pts


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def write_png(out):
    from PIL import Image, ImageDraw

    s = 1024
    k = s / 108.0
    im = Image.new("RGBA", (s, s), rgb(TEAL))
    d = ImageDraw.Draw(im)

    # launcher icons show the inner 72 of the 108 viewport: scale the drawing up by 1.5 about the centre
    def p(x, y):
        return ((x - 54) * 1.5 + 54) * k, ((y - 54) * 1.5 + 54) * k

    def stroke(pts, colour, width, caps):
        r = width * 1.5 * k / 2
        dense = []
        for a, b in zip(pts, pts[1:]):
            for i in range(8):
                t = i / 8
                dense.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
        dense.append(pts[-1])
        if not caps:
            dense = dense[3:-3]
        for q in dense:
            x, y = p(*q)
            d.ellipse([x - r, y - r, x + r, y + r], fill=rgb(colour))

    for colour, seam, cmds in STRANDS:
        pts = sample(cmds)
        if seam:
            stroke(pts, SEAM, SEAM_W, False)
        stroke(pts, colour, ROPE_W, True)
    im.resize((512, 512), Image.LANCZOS).save(out)
    print("icon written", out)


if __name__ == "__main__":
    if sys.argv[1] == "--xml":
        write_xml(os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable", "ic_launcher_foreground.xml"))
    else:
        write_png(sys.argv[1])
