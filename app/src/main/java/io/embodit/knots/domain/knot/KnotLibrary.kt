package io.embodit.knots.domain.knot

/**
 * The four knots of v1 (design `models.list`, control points from the design station's `knots.preview.js`).
 * Units: millimetres in the rope frame (x to the user's right hand, y up, z towards the user).
 *
 * Control point kinds (as in the preview engine):
 * - [Ctl.Flat]  `P(x, y, lvl, L)`: z = lvl × 0.6 d × w, w = 0..1 once the other strand of crossing L has arrived;
 * - [Ctl.Cyl]   `C(θ°, y, rk | lvl, L, dy)`: on a cylinder about the y axis (θ 0 = front, 90 = right); radius rk × d
 *               (the reef's helix) or the post (R + d/2, lifted 1.1 d when lvl > 0);
 * - [Ctl.Front] `F(x, y, dy)`: on the tangent plane in front of the post (z = R + d/2);
 * - [Ctl.Free]  `Z(x, y, z, dy)`: any 3D point; v0.1.2 knots (generated by tools/knotlab.py) add `dx` and `zd`.
 * `dx`, `dy`, `zd` are in units of d (crossing lifts and wrap radii scale with the rope).
 */
sealed class Ctl {
    data class Flat(val x: Float, val y: Float, val lvl: Int = 0, val label: String? = null) : Ctl()

    data class Cyl(val thetaDeg: Float, val y: Float, val rk: Float? = null, val lvl: Int = 0, val label: String? = null, val dy: Float = 0f) : Ctl()

    data class Front(val x: Float, val y: Float, val dy: Float = 0f) : Ctl()

    data class Free(val x: Float, val y: Float, val z: Float, val dy: Float = 0f, val dx: Float = 0f, val zd: Float = 0f) : Ctl()

    val crossing: String?
        get() =
            when (this) {
                is Flat -> label
                is Cyl -> label
                else -> null
            }
}

enum class Category(val id: String) {
    ALL("all"),
    BASIC("basic"),
    CAMPING("camping"),
    BOATING("boating"),
    CLIMBING("climbing");

    companion object {
        fun byId(id: String): Category? = entries.firstOrNull { it.id == id }
    }
}

enum class StepType { LAY, TIGHTEN }

data class KnotStep(val zh: String, val en: String, val mnemonicZh: String, val type: StepType, val end: Int = -1)

/**
 * How the tighten step pulls the knot's core together: control points in [ranges] are drawn towards (cx, cy) by k (x)
 * and ky (y). [lambda] is the share of that pull actually used per rope diameter (4 / 8 / 11 mm), the largest share
 * that keeps every pair of strands at least 0.9 d apart (found with the geometry tests, `KnotEngineTest`).
 */
data class Tighten(val ranges: List<IntRange>, val cx: Float, val cy: Float, val k: Float, val ky: Float, val lambda: Map<Int, Float>)

/** A "pull here" arrow of the tighten step: where (mm, rope frame) and which way (unit x, y). */
data class PullArrow(val x: Float, val y: Float, val dx: Float, val dy: Float)

data class Knot(
    val id: String,
    val zh: String,
    val en: String,
    val aliasZh: String,
    val aliasEn: String,
    val categories: Set<Category>,
    val difficulty: Int,
    val useZh: String,
    val useEn: String,
    val cautionZh: String,
    val cautionEn: String,
    val checkZh: String,
    val checkEn: String,
    val pts: List<Ctl>,
    /** Control point the tip rests on in the start shape. */
    val start: Int,
    val steps: List<KnotStep>,
    val tighten: Tighten,
    val pulls: List<PullArrow>,
    /** Clove hitch: a virtual post (Ø 40 mm × 0.24 m) at the origin; the rope frame sits [lowerMm] lower. */
    val post: Boolean = false,
    val lowerMm: Float = 0f,
    /** Square knot: the s = 0 end is the blue end. */
    val twoColor: Boolean = false,
    /** Extra planar spread of the knot (the bowline is drawn 1.3× so its strands keep 0.9 d apart). */
    val spread: Float = 1f,
    /** The first [anchors] control points (the straight standing part) keep their spacing instead of scaling with d. */
    val anchors: Int = 0,
    /** Two-rope knots (v0.1.3, bends): control points from [rope2] on are a second rope (blue first rope, red second). */
    val rope2: Int = -1,
    /** The second rope is laid up to this control point before the first is tied (its standing part). */
    val rope2Shown: Int = -1,
) {
    val twoRopes: Boolean
        get() = rope2 > 0
}

